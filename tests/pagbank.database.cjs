const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const ts = require('typescript');
const { randomUUID } = require('node:crypto');
const resolve = Module._resolveFilename;
Module._resolveFilename = function(name, ...args) { return resolve.call(this, name.startsWith('@/') ? path.join(process.cwd(), 'src', name.slice(2)) : name, ...args); };
require.extensions['.ts'] = (mod, filename) => mod._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText, filename);
let session = null;
require.cache[require.resolve('../src/auth.ts')] = { exports: { auth: async () => session } };
const { prisma } = require('../src/lib/prisma.ts');
const { encryptCredentials } = require('../src/lib/encryption.ts');
const sales = require('../src/app/api/sales/route.ts');
const payments = require('../src/app/api/sales/[id]/payments/route.ts');
const status = require('../src/app/api/sales/[id]/payments/[attemptId]/status/route.ts');
const cancel = require('../src/app/api/sales/[id]/cancel/route.ts');
const confirm = require('../src/app/api/sales/[id]/payments/[attemptId]/confirm/route.ts');
const settings = require('../src/app/api/settings/payments/route.ts');
const { releaseExpiredSales } = require('../src/lib/sales/reservations.ts');
const { releaseExpiredSaleWithProviderCheck } = require('../src/lib/sales/provider-order-lifecycle.ts');
const { applyPaymentResult } = require('../src/lib/sales/payment-result.ts');
const request = data => new Request('https://qa.invalid/api', { method: 'POST', body: JSON.stringify(data) });
const identity = id => ({ params: { id } });
const customer = { customerName: 'QA PagBank', customerEmail: 'qa@example.invalid', customerDocument: '12345678909' };

(async () => {
  const tenants = [];
  const originalFetch = globalThis.fetch;
  let providerState = 'WAITING', providerAmount = 1000, timeout = false, posts = 0;
  globalThis.fetch = async (url, options) => {
    assert.ok(url.startsWith('https://sandbox.api.pagseguro.com/orders'));
    assert.equal(options.headers.Authorization, 'Bearer QA_TOKEN');
    if (options.method === 'POST') { posts++; if (timeout) throw new Error('QA timeout'); }
    const id = options.method === 'POST' ? `ORDE_QA_${posts}` : decodeURIComponent(url.split('/').pop());
    return Response.json({ id, charges: [{ status: providerState, payment_method: { type: 'PIX' }, amount: { value: providerAmount, currency: 'BRL', summary: { paid: providerState === 'PAID' ? providerAmount : 0, refunded: 0 } }, qr_code: { text: 'QA_PIX' } }] });
  };
  try {
    for (let i = 0; i < 2; i++) tenants.push(await prisma.tenant.create({ data: { name: 'QA PagBank', slug: `qa-pagbank-${randomUUID()}` } }));
    const tenantId = tenants[0].id;
    const owner = await prisma.user.create({ data: { tenant_id: tenantId, name: 'QA owner', email: 'qa@example.invalid', role: 'owner' } });
    session = { user: { id: owner.id, tenantId, role: 'owner' } };
    await prisma.cashRegisterSession.create({ data: { tenant_id: tenantId, user_id: owner.id, initial_amount: '0' } });
    const product = await prisma.product.create({ data: { tenant_id: tenantId, name: 'QA Item', price: '10', unit_of_measure: 'un', stock_quantity: '100' } });
    await prisma.paymentGatewayConfig.create({ data: { tenant_id: tenantId, provider: 'pagbank', environment: 'sandbox', is_active: true, is_default: true, encrypted_credentials: encryptCredentials({ token: 'QA_TOKEN' }) } });
    const newSale = async () => { const r = await sales.POST(request({ idempotencyKey: randomUUID(), items: [{ productId: product.id, quantity: 1 }] })); assert.equal(r.status, 201); return (await r.json()).sale.id; };
    const charge = (id, key = randomUUID()) => payments.POST(request({ ...customer, provider: 'pagbank', method: 'pix', channel: 'online', idempotencyKey: key }), identity(id));
    const first = await newSale();
    const key = randomUUID();
    const response = await charge(first, key); assert.equal(response.status, 201);
    const data = await response.json(); assert.equal(data.payment.pixCopyPaste, 'QA_PIX');
    assert.equal(data.attempt.status, 'pending');
    assert.equal((await charge(first, key)).status, 200); assert.equal(posts, 1);
    const context = { params: { id: first, attemptId: data.attempt.id } };
    providerAmount = 999;
    assert.equal((await status.GET(null, context)).status, 502, 'wrong amount cannot approve');
    assert.equal((await prisma.sale.findUniqueOrThrow({ where: { id: first } })).status, 'pending');
    providerAmount = 1000; providerState = 'PAID';
    assert.equal((await (await status.GET(null, context)).json()).saleCompleted, true);
    assert.equal((await (await status.GET(null, context)).json()).saleCompleted, true);
    await prisma.$transaction(tx => applyPaymentResult(tx, { tenantId, saleId: first, attemptId: data.attempt.id, provider: 'pagbank', method: 'pix', result: { status: 'pending' } }));
    assert.equal((await prisma.paymentAttempt.findUniqueOrThrow({ where: { id: data.attempt.id } })).status, 'APPROVED', 'late response must never downgrade paid attempt');
    session.user.tenantId = tenants[1].id; assert.equal((await status.GET(null, context)).status, 404); session.user.tenantId = tenantId;
    providerState = 'WAITING';
    const second = await newSale(); assert.equal((await charge(second)).status, 201);
    assert.equal((await cancel.POST(request({}), identity(second))).status, 409);
    await prisma.sale.update({ where: { id: second }, data: { expires_at: new Date(Date.now() - 1000) } });
    assert.equal(await prisma.$transaction(tx => releaseExpiredSales(tx, tenantId, new Date())), 0);
    assert.equal((await releaseExpiredSaleWithProviderCheck(tenantId, second, new Date())).released, false);
    providerState = 'CANCELED'; assert.equal((await releaseExpiredSaleWithProviderCheck(tenantId, second, new Date())).released, true);
    assert.equal((await prisma.product.findUniqueOrThrow({ where: { id: product.id } })).stock_quantity.toString(), '99');
    providerState = 'WAITING';
    const third = await newSale(); const before = posts;
    const concurrent = await Promise.all([charge(third), charge(third)]);
    assert.deepEqual(concurrent.map(r => r.status).sort(), [201,409]); assert.equal(posts, before + 1);
    const pending = await prisma.paymentAttempt.findFirstOrThrow({ where: { tenant_id: tenantId, sale_id: third } });
    assert.equal((await confirm.POST(null, { params: { id: third, attemptId: pending.id } })).status, 409, 'PagBank cannot be manually approved');
    assert.equal((await settings.POST(request({ provider: 'pagbank', environment: 'production', isActive: true, credentials: {} }))).status, 409, 'pending orders retain their environment');
    providerState = 'CANCELED'; assert.equal((await cancel.POST(request({}), identity(third))).status, 200);
    const fourth = await newSale(); timeout = true;
    const unknown = await charge(fourth); assert.equal(unknown.status, 502);
    const uncertain = await unknown.json(); assert.equal(uncertain.attempt.status, 'pending'); assert.equal(uncertain.attempt.failureCode, 'RECONCILIATION_REQUIRED');
    assert.equal((await charge(fourth)).status, 409); assert.equal((await cancel.POST(request({}), identity(fourth))).status, 409);
    await prisma.sale.update({ where: { id: fourth }, data: { expires_at: new Date(Date.now() - 1000) } });
    assert.equal(await prisma.$transaction(tx => releaseExpiredSales(tx, tenantId, new Date())), 0);
    assert.equal((await releaseExpiredSaleWithProviderCheck(tenantId, fourth, new Date())).released, false);
    console.log('PASS PagBank QR creation, tenant isolation, paid-only completion, amounts, concurrency, idempotency, manual confirmation refusal, pending cancellation/expiry protection and uncertain outcomes');
  } finally {
    globalThis.fetch = originalFetch;
    const ids = tenants.map(t => t.id);
    await prisma.paymentAttempt.deleteMany({ where: { tenant_id: { in: ids } } });
    await prisma.saleItem.deleteMany({ where: { sale: { tenant_id: { in: ids } } } });
    await prisma.sale.deleteMany({ where: { tenant_id: { in: ids } } });
    await prisma.cashRegisterSession.deleteMany({ where: { tenant_id: { in: ids } } });
    await prisma.tenant.deleteMany({ where: { id: { in: ids } } });
    await prisma.$disconnect();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });

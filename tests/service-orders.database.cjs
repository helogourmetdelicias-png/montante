// Integration with the configured database. All writes belong to disposable tenants.
require('@next/env').loadEnvConfig(process.cwd());
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const ts = require('typescript');
const resolve = Module._resolveFilename;
Module._resolveFilename = function(name, ...args) { return resolve.call(this, name.startsWith('@/') ? path.join(process.cwd(), 'src', name.slice(2)) : name, ...args); };
require.extensions['.ts'] = (mod, filename) => mod._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText, filename);
const { PrismaClient, Prisma } = require('@prisma/client');
const db = new PrismaClient();
require.cache[require.resolve('../src/lib/prisma.ts')] = { exports: { prisma: db } };
let session;
require.cache[require.resolve('../src/auth.ts')] = { exports: { auth: async () => session } };
const { saveServiceOrder, serializeServiceOrder } = require('../src/lib/service-orders/service.ts');
const { completeCashPayment } = require('../src/lib/sales/cash-payment.ts');
const { applyPaymentResult } = require('../src/lib/sales/payment-result.ts');
const { cancelSaleAndRestore } = require('../src/lib/sales/reservations.ts');
const { POST: checkout } = require('../src/app/api/service-orders/[id]/checkout/route.ts');
const { GET: detail } = require('../src/app/api/service-orders/[id]/route.ts');
const { runSerializableTransaction: transaction } = require('../src/lib/database/transactions.ts');
const tenantIds = [];
async function main() {
  const suffix = randomUUID();
  const a = await db.tenant.create({ data: { name: 'Fixture OS A', slug: `os-a-${suffix}`, niche: 'IT_SUPPORT' } }); tenantIds.push(a.id);
  const b = await db.tenant.create({ data: { name: 'Fixture OS B', slug: `os-b-${suffix}`, niche: 'PHONE_REPAIR' } }); tenantIds.push(b.id);
  const user = await db.user.create({ data: { tenant_id: a.id, name: 'Técnico fixture', email: `os-${suffix}@example.invalid`, role: 'owner' } });
  session = { user: { id: user.id, tenantId: a.id, role: 'owner' } };
  const register = await db.cashRegisterSession.create({ data: { tenant_id: a.id, user_id: user.id, initial_amount: 0 } });
  const product = await db.product.create({ data: { tenant_id: a.id, name: 'Peça fixture', unit_of_measure: 'UN', price: '25.90', stock_quantity: 5 } });
  const foreign = await db.product.create({ data: { tenant_id: b.id, name: 'Outra loja', unit_of_measure: 'UN', price: 5, stock_quantity: 8 } });
  const input = { clientName: 'Cliente fixture', clientPhone: '21999999999', deviceType: 'Notebook', deviceBrandModel: 'Modelo fixture', serialNumberImei: 'FIXTURE', reportedDefect: 'Não liga', aestheticCondition: 'Riscos', devicePassword: 'fixture-secret-only', laborTotal: 50, photoUrls: ['https://example.invalid/photo.jpg'], parts: [{ productId: product.id, quantity: 2 }] };
  let order = await transaction(tx => saveServiceOrder(tx, a.id, input));
  assert.equal(order.grand_total.toFixed(2), '101.80');
  assert.equal((await db.product.findUniqueOrThrow({ where: { id: product.id } })).stock_quantity.toNumber(), 5);
  assert.ok(!order.device_password_encrypted.includes(input.devicePassword));
  assert.ok(!JSON.stringify(serializeServiceOrder(order)).includes(input.devicePassword));
  await assert.rejects(transaction(tx => saveServiceOrder(tx, a.id, { ...input, parts: [{ productId: foreign.id, quantity: 1 }] })), /Peça não encontrada/);
  const other = await detail(new Request('https://test.invalid'), { params: Promise.resolve({ id: order.id }) }); assert.equal(other.status, 200);
  session.user.tenantId = b.id;
  assert.equal((await detail(new Request('https://test.invalid'), { params: Promise.resolve({ id: order.id }) })).status, 404);
  session.user.tenantId = a.id;
  const staleVersion = order.version;
  order = await transaction(tx => saveServiceOrder(tx, a.id, input, { id: order.id, version: order.version, status: 'READY' }));
  await assert.rejects(transaction(tx => saveServiceOrder(tx, a.id, input, { id: order.id, version: staleVersion, status: 'READY' })), /alterada/);
  const pull = () => checkout(new Request('https://test.invalid/checkout', { method: 'POST' }), { params: Promise.resolve({ id: order.id }) });
  const pulls = await Promise.all([pull(), pull()]);
  const data = await Promise.all(pulls.map(async res => { assert.equal(res.status, 200); return res.json(); }));
  assert.equal(data[0].saleId, data[1].saleId);
  assert.equal(await db.sale.count({ where: { tenant_id: a.id, service_order_id: order.id } }), 1);
  const saleId = data[0].saleId;
  await assert.rejects(transaction(tx => saveServiceOrder(tx, a.id, input, { id: order.id, version: order.version + 1, status: 'READY' })), /venda vinculada/);
  const partialKey = randomUUID();
  const partial = { tenantId: a.id, saleId, idempotencyKey: partialKey, receivedCents: 3000, appliedCents: 3000 };
  assert.equal((await transaction(tx => completeCashPayment(tx, partial))).saleCompleted, false);
  assert.equal((await transaction(tx => completeCashPayment(tx, partial))).replayed, true);
  assert.equal((await db.serviceOrder.findUniqueOrThrow({ where: { id: order.id } })).status, 'READY');
  assert.equal((await db.product.findUniqueOrThrow({ where: { id: product.id } })).stock_quantity.toNumber(), 5);
  const final = { tenantId: a.id, saleId, idempotencyKey: randomUUID(), receivedCents: 8000, appliedCents: 7180 };
  const done = await transaction(tx => completeCashPayment(tx, final)); assert.equal(done.saleCompleted, true); assert.equal(done.changeAmount, '8.20');
  assert.equal((await transaction(tx => completeCashPayment(tx, final))).replayed, true);
  const completed = await db.serviceOrder.findUniqueOrThrow({ where: { id: order.id } }); assert.equal(completed.status, 'COMPLETED'); assert.equal(completed.device_password_encrypted, null);
  assert.equal((await db.product.findUniqueOrThrow({ where: { id: product.id } })).stock_quantity.toNumber(), 3);
  const receipt = await db.sale.findUniqueOrThrow({ where: { id: saleId } }); assert.equal(receipt.cash_register_session_id, register.id); assert.equal(receipt.total_amount.toFixed(2), '101.80');
  // A stock race must roll back payment, sale and order together.
  order = await transaction(tx => saveServiceOrder(tx, a.id, { ...input, parts: [{ productId: product.id, quantity: 1 }] }));
  order = await transaction(tx => saveServiceOrder(tx, a.id, { ...input, parts: [{ productId: product.id, quantity: 1 }] }, { id: order.id, version: order.version, status: 'READY' }));
  const nextCheckout = await (await pull()).json();
  await db.product.update({ where: { id: product.id }, data: { stock_quantity: 0 } });
  await assert.rejects(transaction(tx => completeCashPayment(tx, { tenantId: a.id, saleId: nextCheckout.saleId, idempotencyKey: randomUUID(), receivedCents: 7590, appliedCents: 7590 })), /Estoque insuficiente/);
  assert.equal(await db.paymentAttempt.count({ where: { sale_id: nextCheckout.saleId } }), 0);
  assert.equal((await db.sale.findUniqueOrThrow({ where: { id: nextCheckout.saleId } })).status, 'pending');
  assert.equal((await db.serviceOrder.findUniqueOrThrow({ where: { id: order.id } })).status, 'READY');
  await transaction(tx => cancelSaleAndRestore(tx, a.id, nextCheckout.saleId));
  assert.equal((await db.product.findUniqueOrThrow({ where: { id: product.id } })).stock_quantity.toNumber(), 0, 'cancelamento da cobrança de OS não devolve peça não baixada');
  await db.product.update({ where: { id: product.id }, data: { stock_quantity: 1 } });
  const onlineCheckout = await (await pull()).json();
  const onlineAttempt = await db.paymentAttempt.create({ data: { tenant_id: a.id, sale_id: onlineCheckout.saleId, provider: 'mercadopago', method: 'PIX', channel: 'ONLINE', status: 'PENDING', amount: '75.90', idempotency_key: randomUUID(), external_order_id: `fixture-${randomUUID()}` } });
  await db.product.update({ where: { id: product.id }, data: { stock_quantity: 0 } });
  const deferred = await transaction(tx => applyPaymentResult(tx, { tenantId: a.id, saleId: onlineCheckout.saleId, attemptId: onlineAttempt.id, method: 'pix', result: { status: 'approved', externalId: onlineAttempt.external_order_id } }));
  assert.equal(deferred.saleCompleted, false);
  assert.equal((await db.paymentAttempt.findUniqueOrThrow({ where: { id: onlineAttempt.id } })).status, 'APPROVED', 'aprovação do provedor permanece registrada mesmo sem peças');
  assert.equal((await db.sale.findUniqueOrThrow({ where: { id: onlineCheckout.saleId } })).status, 'pending');
  assert.equal((await db.serviceOrder.findUniqueOrThrow({ where: { id: order.id } })).status, 'READY');
  await db.product.update({ where: { id: product.id }, data: { stock_quantity: 1 } });
  const resumed = await pull(); assert.equal(resumed.status, 200);
  assert.equal((await resumed.json()).href, `/ordens-servico/${order.id}`);
  assert.equal((await db.serviceOrder.findUniqueOrThrow({ where: { id: order.id } })).status, 'COMPLETED');
  assert.equal((await db.product.findUniqueOrThrow({ where: { id: product.id } })).stock_quantity.toNumber(), 0);
  console.log('PASS: nichos, isolamento, senha, totais, checkout concorrente, bloqueio de orçamento, parcial/repetição, troco, baixa única, rollback e cancelamento sem estoque fictício.');
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  if (tenantIds.length) {
    await db.paymentAttempt.deleteMany({ where: { tenant_id: { in: tenantIds } } });
    await db.sale.deleteMany({ where: { tenant_id: { in: tenantIds } } });
    await db.serviceOrder.deleteMany({ where: { tenant_id: { in: tenantIds } } });
    await db.product.deleteMany({ where: { tenant_id: { in: tenantIds } } });
    await db.cashRegisterSession.deleteMany({ where: { tenant_id: { in: tenantIds } } });
    await db.user.deleteMany({ where: { tenant_id: { in: tenantIds } } });
    await db.tenant.deleteMany({ where: { id: { in: tenantIds } } });
    console.log('Fixtures de OS removidas.');
  }
  await db.$disconnect();
});
